#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""LEET 표준점수 ↔ 원점수 역산 · 연도별 난이도 보정.

왜 필요한가
-----------
로스쿨 합격자 성적은 표준점수로 공시된다. 그런데 표준점수는 그 해 응시자
집단에 대한 상대 위치라서, 시험이 쉬웠던 해(원점수 평균 μ가 높은 해)에는
같은 실력이라도 표준점수가 낮게 찍힌다. 따라서 연도가 다른 표준점수를
그대로 빼면 난이도 차이를 실력 차이로 오독하게 된다.

이 스크립트는 연도별 (μ, 만점 표준점수) 두 점으로 선형변환을 복원해
표준점수를 그 해의 원점수로 되돌린다.

변환식 (법전협)
---------------
    언어이해  T = 45 + 9  x (X - mu) / sigma      (30문항)
    추리논증  T = 60 + 12 x (X - mu) / sigma      (40문항)

평균 50 / 표준편차 10이 **아니다**. 영역별로 스케일이 다르고, 그래서
추리논증의 실질 배점이 언어이해의 4/3배다.

⚠ 데이터 신뢰도
----------------
법전협은 원점수 표준편차(sigma)를 공표하지 않는 것으로 보인다. 아래 sigma와
"원점수 1점당 표준점수"는 (mu, 만점 표준점수)에서 역산한 계산값이다.
게다가 이 표의 입력값 자체가 1차 출처 원문 대조를 거치지 않았다.
CONF 열이 'low'인 연도는 사용하지 말 것. 자세한 것은 같은 폴더의
LEET_연도별_난이도보정.md 참조.

사용법
------
    python3 leet_보정.py                 # 보정표 전체 출력
    python3 leet_보정.py 2027 추리 35    # 2027학년도 추리논증 원점수 35점 -> 표준점수
    python3 leet_보정.py 2025 언어 T63   # 2025학년도 언어이해 표준점수 63 -> 원점수
"""

import sys

# 영역 상수: (표준점수 평균 M, 표준점수 SD k, 원점수 만점 X_max)
영역 = {
    "언어": {"M": 45.0, "k": 9.0, "만점": 30},
    "추리": {"M": 60.0, "k": 12.0, "만점": 40},
}

# 학년도별 (원점수 평균 mu, 만점의 표준점수 T_max, 신뢰도)
#   신뢰도 high  : mu와 T_max가 서로 다른 보도에서 일치, 합계 검증 통과
#   신뢰도 mid   : 단일 출처이거나 사소한 충돌(소수 둘째 자리)
#   신뢰도 low   : 출처 간 충돌 미해소 또는 추정치 -> 역산 금지
DATA = {
    "언어": {
        2021: (15.2, None, "low"),    # T_max 미확보(만점자 없음, 29점=78.1)
        2022: (16.6, None, "low"),    # T_max 미확보
        2023: (16.9, 72.5, "mid"),
        2024: (15.25, 80.9, "high"),  # 합계 178.40 검증 통과
        2025: (17.03, 73.5, "high"),  # 합계 165.00 검증 통과
        2026: (17.18, 73.0, "low"),   # T_max 충돌: 73.0 / 73.6 / 74.6
        2027: (None, 70.5, "low"),    # mu 미확보 + 보도 간 모순
    },
    "추리": {
        2021: (21.9, None, "low"),
        2022: (22.7, 96.8, "mid"),    # mu 충돌: 22.7 / 22.6
        2023: (23.15, 94.8, "mid"),   # T_max 충돌: 94.8 / 94.7
        2024: (22.20, 97.5, "high"),  # 합계 178.40 검증 통과
        2025: (25.08, 91.5, "high"),  # 합계 165.00 검증 통과
        2026: (22.83, 97.9, "low"),   # T_max 충돌: 97.9 / 99.5
        2027: (24.5, 92.6, "low"),    # mu가 추정치([C])
    },
}

# 2026학년도 만점 표준점수 대립가설. 두 조합 모두 합계 172.5와 일치해
# 산술만으로는 판별 불가 -> 민감도 확인용으로만 둔다.
대립가설_2026 = {"언어": 74.6, "추리": 99.5}


def 계수(과목, 학년도, T_max=None):
    """그 해의 sigma와 '원점수 1점당 표준점수' d를 돌려준다.

    d = k / sigma = (T_max - M) / (X_max - mu)
    """
    s = 영역[과목]
    mu, 기본_Tmax, conf = DATA[과목][학년도]
    T_max = T_max if T_max is not None else 기본_Tmax
    if mu is None or T_max is None:
        return None
    여유 = s["만점"] - mu               # 평균에서 만점까지의 원점수 거리
    d = (T_max - s["M"]) / 여유          # 원점수 1점당 표준점수
    sigma = s["k"] / d
    return {"mu": mu, "T_max": T_max, "sigma": sigma, "d": d, "conf": conf}


def 원점수_to_표점(과목, 학년도, X, T_max=None):
    c = 계수(과목, 학년도, T_max)
    if c is None:
        return None
    return 영역[과목]["M"] + (X - c["mu"]) * c["d"]


def 표점_to_원점수(과목, 학년도, T, T_max=None):
    """원점수 = 만점 - (만점 표준점수 - 내 표준점수) / d"""
    c = 계수(과목, 학년도, T_max)
    if c is None:
        return None
    return 영역[과목]["만점"] - (c["T_max"] - T) / c["d"]


def 표_계수():
    print("\n[1] 연도별 변환 계수 (sigma와 d는 역산한 계산값)\n")
    for 과목 in ("언어", "추리"):
        s = 영역[과목]
        이름 = "언어이해" if 과목 == "언어" else "추리논증"
        print(f"  ── {이름}  ({s['만점']}문항, T = {s['M']:.0f} + {s['k']:.0f}Z)")
        print(f"  {'학년도':<8}{'원점수평균':>10}{'만점표점':>10}{'sigma':>9}{'1점당':>8}  신뢰도")
        for 학년도 in sorted(DATA[과목]):
            mu, T_max, conf = DATA[과목][학년도]
            c = 계수(과목, 학년도)
            if c is None:
                mu_s = f"{mu:.2f}" if mu is not None else "미확보"
                T_s = f"{T_max:.1f}" if T_max is not None else "미확보"
                print(f"  {학년도:<8}{mu_s:>10}{T_s:>10}{'—':>9}{'—':>8}  {conf}  ← 역산 불가")
            else:
                mark = "  ← 사용 금지" if conf == "low" else ""
                print(f"  {학년도:<8}{c['mu']:>10.2f}{c['T_max']:>10.1f}"
                      f"{c['sigma']:>9.2f}{c['d']:>8.3f}  {conf}{mark}")
        print()


def 표_동일원점수(과목, 원점수목록):
    """같은 원점수가 해마다 몇 점의 표준점수가 되는지 — 난이도 왜곡의 실체."""
    학년도목록 = [y for y in sorted(DATA[과목]) if 계수(과목, y)]
    print(f"\n[2] 같은 원점수의 연도별 표준점수 — {과목}\n")
    머리 = "  원점수 " + "".join(f"{y:>9}" for y in 학년도목록) + "     최대격차"
    print(머리)
    print("  " + "─" * (len(머리) - 2))
    for X in 원점수목록:
        값 = [원점수_to_표점(과목, y, X) for y in 학년도목록]
        폭 = max(값) - min(값)
        print(f"  {X:>5}  " + "".join(f"{v:>9.1f}" for v in 값) + f"{폭:>11.1f}점")
    print("\n  → 같은 실력(원점수)인데 연도별 표준점수가 이만큼 다르다.")
    print("     연도가 다른 표준점수를 그대로 빼면 이 차이를 실력차로 오독한다.")


def 표_합계(조합목록):
    """합계 표준점수 기준 — 로스쿨 정량 산식이 실제로 쓰는 값.

    영역별 왜곡이 같은 방향으로 겹치는 해가 있어, 합계 격차는 영역 하나만
    볼 때보다 커진다.
    """
    학년도목록 = [y for y in sorted(DATA["언어"])
                if 계수("언어", y) and 계수("추리", y)]
    print("\n[3] 같은 원점수 조합의 연도별 표준점수 합계\n")
    머리 = "  언어+추리 " + "".join(f"{y:>9}" for y in 학년도목록) + "     최대격차"
    print(머리)
    print("  " + "─" * (len(머리) - 2))
    for 언, 추 in 조합목록:
        값 = [원점수_to_표점("언어", y, 언) + 원점수_to_표점("추리", y, 추)
             for y in 학년도목록]
        폭 = max(값) - min(값)
        print(f"  {언:>4}+{추:<4} " + "".join(f"{v:>9.1f}" for v in 값) + f"{폭:>11.1f}점")
    print("\n  → 합계에서는 영역별 왜곡이 겹쳐 격차가 더 벌어진다.")
    print("     참고: 기존 분석 문서가 다룬 '정량 격차'의 실질 가치가")
    print("     LEET 표점 7~13점 규모였다. 난이도 보정만으로 그 크기가 나온다.")



def 표_고정표점(목표=130.0):
    """표준점수 합계를 고정하고, 그 해에 필요한 원점수를 역산한다.

    원점수를 고정하면 표준점수가 흔들리고, 표준점수를 고정하면 원점수가
    흔들린다. 같은 왜곡을 지원자 관점에서 보는 쪽이 이것이다 —
    "그 해에 이 점수를 받으려면 몇 개를 맞혀야 했나".

    두 영역 배분이 정해지지 않으므로 세 가지 기준으로 낸다.
      균형   : 두 영역 Z가 같은 경우 (합계 = 105 + 21Z 이므로 Z가 유일하게 결정된다)
      추리집중: 언어를 평균만 받고 나머지를 추리로 채우는 경우
      언어집중: 추리를 평균만 받고 나머지를 언어로 채우는 경우
    """
    학년도목록 = [y for y in sorted(DATA["언어"])
                if 계수("언어", y) and 계수("추리", y)]
    Z = (목표 - 105.0) / 21.0          # 45+9Z + 60+12Z = 105+21Z
    print(f"\n[5] 표준점수 합계 {목표:.0f}을 받으려면 그 해에 원점수 몇 개가 필요했나\n")
    print(f"  (균형 = 두 영역 Z 동일, Z={Z:.3f})\n")
    print(f"  {'학년도':<8}{'언어':>8}{'추리':>8}{'원점수 합':>11}   "
          f"{'추리집중':>10}{'언어집중':>10}")
    print("  " + "─" * 60)
    합계목록 = []
    for y in 학년도목록:
        cl, cr = 계수("언어", y), 계수("추리", y)
        x언 = cl["mu"] + Z * cl["sigma"]
        x추 = cr["mu"] + Z * cr["sigma"]
        균형 = x언 + x추
        합계목록.append((y, 균형))
        # 한쪽을 평균으로 고정했을 때 반대쪽에 필요한 원점수
        추리집중 = cl["mu"] + (cr["mu"] + (목표 - 105.0) / cr["d"])
        언어집중 = (cl["mu"] + (목표 - 105.0) / cl["d"]) + cr["mu"]
        print(f"  {y:<8}{x언:>8.1f}{x추:>8.1f}{균형:>11.1f}   "
              f"{추리집중:>10.1f}{언어집중:>10.1f}")
    lo = min(합계목록, key=lambda t: t[1])
    hi = max(합계목록, key=lambda t: t[1])
    print(f"\n  → 가장 적게 든 해 {lo[0]}학년도 {lo[1]:.1f}개, "
          f"가장 많이 든 해 {hi[0]}학년도 {hi[1]:.1f}개 "
          f"— 차이 {hi[1]-lo[1]:.1f}개")
    print(f"     같은 표준점수 {목표:.0f}인데 실제로 맞혀야 한 문항 수가 "
          f"{hi[1]-lo[1]:.1f}개 다르다.")
    print("     '추리집중/언어집중'은 한 영역을 평균만 받았다고 가정한 극단값이다.")

def 민감도_2026():
    print("\n[4] 2026학년도 민감도 — 만점 표준점수 출처 충돌의 영향\n")
    for 과목, 대립 in 대립가설_2026.items():
        기본 = DATA[과목][2026][1]
        s = 영역[과목]
        X = 25 if 과목 == "언어" else 35
        a = 원점수_to_표점(과목, 2026, X)
        b = 원점수_to_표점(과목, 2026, X, T_max=대립)
        print(f"  {과목}  원점수 {X}점 → 만점표점 {기본:.1f} 가정: {a:.1f} / "
              f"{대립:.1f} 가정: {b:.1f}   (차이 {abs(a-b):.1f}점)")
    print("\n  → 어느 쪽이 맞는지 확정 전에는 2026학년도 역산값을 쓰지 말 것.")


def main():
    if len(sys.argv) == 4:
        학년도, 과목, 값 = int(sys.argv[1]), sys.argv[2], sys.argv[3]
        과목 = "언어" if 과목.startswith("언어") else "추리"
        if 값.upper().startswith("T"):
            T = float(값[1:])
            X = 표점_to_원점수(과목, 학년도, T)
            print(f"{학년도}학년도 {과목} 표준점수 {T} → 원점수 약 {X:.2f}점"
                  if X is not None else "역산 불가 (해당 연도 데이터 부족)")
        else:
            X = float(값)
            T = 원점수_to_표점(과목, 학년도, X)
            print(f"{학년도}학년도 {과목} 원점수 {X}점 → 표준점수 약 {T:.1f}"
                  if T is not None else "역산 불가 (해당 연도 데이터 부족)")
        return

    if len(sys.argv) == 2 and sys.argv[1].replace(".","").isdigit():
        표_고정표점(float(sys.argv[1]));  return

    print("=" * 72)
    print("LEET 연도별 난이도 보정 — 표준점수 ↔ 원점수")
    print("⚠ 1차 출처 원문 미대조. 지원 판단 전 leet.or.kr·akls.kr 원문 확인 필수.")
    print("=" * 72)
    표_계수()
    표_동일원점수("언어", [18, 20, 22, 24, 25, 26, 27])
    표_동일원점수("추리", [26, 28, 30, 32, 34, 35, 36])
    표_합계([(20, 28), (22, 30), (24, 32), (25, 35), (26, 36), (27, 37)])
    표_고정표점(130.0)
    민감도_2026()


if __name__ == "__main__":
    main()
