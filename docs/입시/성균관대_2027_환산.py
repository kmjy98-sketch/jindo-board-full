def _interp(x, tbl):
    """표에 없는 값은 인접 급간 사이 선형보간 (요강: 급간 점수는 비례 반영)."""
    ks = sorted(tbl)
    if x >= ks[-1]: return tbl[ks[-1]]
    if x <= ks[0]:  return tbl[ks[0]]
    if x in tbl:    return tbl[x]
    lo = max(k for k in ks if k < x)
    hi = min(k for k in ks if k > x)
    return tbl[lo] + (tbl[hi] - tbl[lo]) * (x - lo) / (hi - lo)


def leet환산(표준점수합: float) -> float:
    """LEET 표준점수 합(언어이해+추리논증) → 환산점수. 소수점 반올림 후 조회."""
    return round(_interp(round(표준점수합), _LEET), 2)


def gpa환산(백분위: float) -> float:
    """학부 백분위 → 환산점수. 백분위는 소수점 둘째 자리에서 반올림."""
    return round(_interp(round(백분위, 1), _GPA), 3)


def 정량(표준점수합: float, gpa백분위: float) -> dict:
    l, g = leet환산(표준점수합), gpa환산(gpa백분위)
    return {"LEET": l, "GPA": g, "총점": round(l + g, 3)}


